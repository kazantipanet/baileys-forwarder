// ==================================================
// ПЕРЕВІРКА ТЕКСТОВОГО ПОВІДОМЛЕННЯ
// ==================================================

function isTextMessage(input) {

    // Якщо передали просто рядок
    if (
        typeof input === 'string'
    ) {

        return (
            input.trim().length > 0
        );
    }


    // Якщо це не об'єкт
    if (
        !input ||
        typeof input !== 'object'
    ) {

        return false;
    }


    // Отримуємо текст
    const text =
        typeof input.text === 'string'
            ? input.text.trim()
            : '';


    // Немає тексту
    if (!text) {

        return false;
    }


    // ------------------------------------------
    // ДОЗВОЛЕНІ ТИПИ WHATSAPP
    // ------------------------------------------

    const allowedTypes = [

        'conversation',

        'extendedTextMessage'

    ];


    // Якщо тип повідомлення відомий —
    // дозволяємо тільки звичайний текст
    if (
        input.messageType &&
        !allowedTypes.includes(
            input.messageType
        )
    ) {

        return false;
    }


    return true;
}


// ==================================================
// ОТРИМАННЯ ТЕКСТУ
// ==================================================

function extractText(input) {

    if (
        typeof input === 'string'
    ) {

        return input.trim();
    }


    if (
        input &&
        typeof input.text === 'string'
    ) {

        return input.text.trim();
    }


    return '';
}


// ==================================================
// ПОШУК ОПЕРАТИВНИХ КЛЮЧОВИХ СЛІВ
// ==================================================

function hasOperationalKeywords(
    text
) {

    const normalized =
        String(text)
            .toLowerCase()
            .replace(/\s+/g, ' ')
            .trim();


    if (!normalized) {

        return false;
    }


    return OPERATIONAL_KEYWORDS.some(
        keyword =>
            normalized.includes(
                keyword
            )
    );
}


// ==================================================
// ОСНОВНА ПЕРЕВІРКА
// ==================================================

function checkRelevance(input) {

    // ------------------------------------------
    // 1. Тільки текст
    // ------------------------------------------

    if (
        !isTextMessage(input)
    ) {

        return {

            relevant: false,

            reason:
                'non_text_message',

            text: ''

        };
    }


    // ------------------------------------------
    // 2. Отримуємо текст
    // ------------------------------------------

    const text =
        extractText(input);


    // ------------------------------------------
    // 3. Перевіряємо оперативні ознаки
    // ------------------------------------------

    const relevant =
        hasOperationalKeywords(
            text
        );


    if (!relevant) {

        return {

            relevant: false,

            reason:
                'no_operational_keywords',

            text

        };
    }


    // ------------------------------------------
    // 4. Повідомлення релевантне
    // ------------------------------------------

    return {

        relevant: true,

        reason:
            'operational_message',

        text

    };
}


